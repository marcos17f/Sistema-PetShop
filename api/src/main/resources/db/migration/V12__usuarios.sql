-- Logins por pessoa (dono e funcionários). A conta principal (PAINEL_USUARIO/PAINEL_SENHA no servidor) continua
-- existindo como dono e conta de recuperação. Senhas só como hash bcrypt.
CREATE TABLE usuario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_id     BIGINT       NOT NULL REFERENCES loja (id),
    nome        VARCHAR(80)  NOT NULL,
    login       VARCHAR(40)  NOT NULL UNIQUE,
    senha_hash  VARCHAR(100) NOT NULL,
    papel       VARCHAR(20)  NOT NULL,
    ativo       BOOLEAN      DEFAULT TRUE NOT NULL,
    criado_em   TIMESTAMP WITH TIME ZONE NOT NULL
);
