CREATE TABLE loja (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug      VARCHAR(80)  NOT NULL UNIQUE,
    nome      VARCHAR(120) NOT NULL,
    whatsapp  VARCHAR(20)
);

CREATE TABLE tutor (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_id    BIGINT       NOT NULL REFERENCES loja (id),
    nome       VARCHAR(120) NOT NULL,
    whatsapp   VARCHAR(20)  NOT NULL,
    endereco   VARCHAR(200),
    cpf        VARCHAR(14),
    origem     VARCHAR(40),
    criado_em  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_tutor_loja ON tutor (loja_id);

CREATE TABLE pet (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tutor_id              BIGINT       NOT NULL REFERENCES tutor (id),
    nome                  VARCHAR(80)  NOT NULL,
    especie               VARCHAR(20)  NOT NULL,
    raca                  VARCHAR(80),
    peso_kg               DOUBLE PRECISION,
    observacoes           VARCHAR(500),
    intervalo_banho_dias  INTEGER,
    ultimo_banho          DATE
);
CREATE INDEX ix_pet_tutor ON pet (tutor_id);

CREATE TABLE aplicacao_vacina (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id       BIGINT      NOT NULL REFERENCES pet (id),
    vacina       VARCHAR(80) NOT NULL,
    dose         VARCHAR(40),
    aplicada_em  DATE        NOT NULL,
    proxima_em   DATE
);
CREATE INDEX ix_vacina_proxima ON aplicacao_vacina (proxima_em);

CREATE TABLE agendamento (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_id    BIGINT       NOT NULL REFERENCES loja (id),
    pet_id     BIGINT       NOT NULL REFERENCES pet (id),
    data       DATE         NOT NULL,
    hora       TIME         NOT NULL,
    tipo       VARCHAR(20)  NOT NULL,
    descricao  VARCHAR(200),
    status     VARCHAR(20)  NOT NULL,
    criado_em  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_agendamento_loja_data ON agendamento (loja_id, data);

-- Lembretes já enviados (por clique ou pela API do WhatsApp), para não repetir.
CREATE TABLE lembrete_enviado (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_id     BIGINT      NOT NULL REFERENCES loja (id),
    chave       VARCHAR(80) NOT NULL,
    enviado_em  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ux_lembrete_chave UNIQUE (loja_id, chave)
);
