-- Histórico de alterações de dados financeiros (lançamentos, preços, valor cobrado no atendimento).
-- Só recebe INSERT: a API não tem rota para editar nem apagar. No PostgreSQL, um gatilho bloqueia
-- UPDATE/DELETE/TRUNCATE (db/postgresql/V4_1__auditoria_imutavel.sql).
-- LGPD: guarda só o usuário do painel e os dados financeiros, nunca nome, telefone ou CPF de cliente.
CREATE TABLE auditoria (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_id      BIGINT        NOT NULL REFERENCES loja (id),
    usuario      VARCHAR(60)   NOT NULL,
    acao         VARCHAR(20)   NOT NULL,
    entidade     VARCHAR(40)   NOT NULL,
    entidade_id  VARCHAR(40)   NOT NULL,
    antes        VARCHAR(1000),
    depois       VARCHAR(1000),
    em           TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_auditoria_loja_em ON auditoria (loja_id, em);
