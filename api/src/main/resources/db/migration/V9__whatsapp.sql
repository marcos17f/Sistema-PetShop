-- WhatsApp: registro de toda mensagem enviada (ou simulada, sem a API oficial) e preferências da loja.
CREATE TABLE mensagem_whatsapp (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_id     BIGINT        NOT NULL REFERENCES loja (id),
    para        VARCHAR(20)   NOT NULL,
    tipo        VARCHAR(20)   NOT NULL,
    texto       VARCHAR(1000) NOT NULL,
    template    VARCHAR(80),
    -- identifica o lembrete (tipo:id:data) para não mandar duas vezes
    chave       VARCHAR(80),
    status      VARCHAR(20)   NOT NULL,
    erro        VARCHAR(300),
    id_externo  VARCHAR(120),
    criado_em   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_mensagem_loja_criado ON mensagem_whatsapp (loja_id, criado_em);
CREATE INDEX ix_mensagem_chave ON mensagem_whatsapp (loja_id, chave);

ALTER TABLE loja ADD COLUMN lembretes_automaticos BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE loja ADD COLUMN resposta_rapida BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE loja ADD COLUMN texto_resposta_rapida VARCHAR(500);
