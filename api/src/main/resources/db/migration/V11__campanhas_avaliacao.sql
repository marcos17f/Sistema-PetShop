-- Campanhas só para quem aceitou promoções (LGPD), com descadastro; pedido de avaliação no Google.
CREATE TABLE campanha (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_id    BIGINT       NOT NULL REFERENCES loja (id),
    titulo     VARCHAR(80)  NOT NULL,
    texto      VARCHAR(600) NOT NULL,
    template   VARCHAR(80)  NOT NULL,
    status     VARCHAR(20)  NOT NULL,
    criada_em  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Um destinatário por campanha (único): o envio continua no dia seguinte sem mandar em dobro.
CREATE TABLE campanha_envio (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campanha_id  BIGINT      NOT NULL REFERENCES campanha (id) ON DELETE CASCADE,
    tutor_id     BIGINT      NOT NULL REFERENCES tutor (id) ON DELETE CASCADE,
    status       VARCHAR(20) NOT NULL,
    enviado_em   TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ux_campanha_envio UNIQUE (campanha_id, tutor_id)
);

-- Descadastro: link pessoal (token aleatório) e data em que o cliente saiu da lista (prova para a LGPD).
ALTER TABLE tutor ADD COLUMN token_descadastro VARCHAR(40);
ALTER TABLE tutor ADD COLUMN descadastrado_em TIMESTAMP WITH TIME ZONE;
CREATE UNIQUE INDEX ux_tutor_token_descadastro ON tutor (token_descadastro);

ALTER TABLE loja ADD COLUMN pedir_avaliacao BOOLEAN DEFAULT FALSE NOT NULL;
