-- Financeiro: categorias, lançamentos (custos fixos, variáveis e receitas avulsas), preço padrão por serviço
-- e valor cobrado no agendamento.

CREATE TABLE categoria_financeira (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_id  BIGINT      NOT NULL REFERENCES loja (id),
    nome     VARCHAR(60) NOT NULL,
    tipo     VARCHAR(20) NOT NULL,
    CONSTRAINT ux_categoria_nome UNIQUE (loja_id, tipo, nome)
);

CREATE TABLE lancamento_financeiro (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_id        BIGINT         NOT NULL REFERENCES loja (id),
    categoria_id   BIGINT         NOT NULL REFERENCES categoria_financeira (id),
    data           DATE           NOT NULL,
    tipo           VARCHAR(20)    NOT NULL,
    descricao      VARCHAR(200),
    valor          NUMERIC(12, 2) NOT NULL,
    recorrente     BOOLEAN        NOT NULL DEFAULT FALSE,
    -- custo fixo recorrente copiado do mês anterior; único para não copiar duas vezes
    copiado_de_id  BIGINT UNIQUE REFERENCES lancamento_financeiro (id) ON DELETE SET NULL,
    criado_em      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_lancamento_loja_data ON lancamento_financeiro (loja_id, data);

CREATE TABLE preco_servico (
    loja_id       BIGINT         NOT NULL REFERENCES loja (id),
    tipo_servico  VARCHAR(20)    NOT NULL,
    valor         NUMERIC(10, 2) NOT NULL,
    PRIMARY KEY (loja_id, tipo_servico)
);

